#!/usr/bin/env node
// Generates plugin/src/ui/ThemeTokens.hpp from course/design-tokens.json.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const t = JSON.parse(fs.readFileSync(path.join(ROOT, "course/design-tokens.json"), "utf8"));
const rgb = (hex) => {
	const n = Number.parseInt(hex.slice(1), 16);
	return `nvgRGB(0x${hex.slice(1, 3)}, 0x${hex.slice(3, 5)}, 0x${hex.slice(5, 7)})`;
};
const f = (x) => (Number.isInteger(x) ? `${x}.f` : `${x}f`);
const theme = (name, c) => `inline Palette ${name}Palette() {\n\tPalette p;\n${Object.entries(c).map(([k, v]) => `\tp.${k} = ${rgb(v)};`).join("\n")}\n\treturn p;\n}`;
const out = `// GENERATED by compiler/gen-theme.mjs from course/design-tokens.json — do not edit.
#pragma once
#include <nanovg.h>

namespace atlas {
namespace tokens {

struct Palette {
	NVGcolor ${Object.keys(t.themes.light).join(", ")};
};

${theme("light", t.themes.light)}

${theme("dark", t.themes.dark)}

inline NVGcolor accent(int part) {
	static const NVGcolor a[] = {${t.accents.map(rgb).join(", ")}};
	if (part < 0 || part >= ${t.accents.length}) part = 0;
	return a[part];
}

${Object.entries(t.type).map(([k, v]) => `constexpr float type_${k} = ${f(v)};`).join("\n")}
${Object.entries(t.panel).map(([k, v]) => `constexpr float panel_${k} = ${f(v)};`).join("\n")}
${Object.entries(t.controls).map(([k, v]) => `constexpr float controls_${k} = ${f(v)};`).join("\n")}
constexpr float motion_glideMs = ${f(t.motion.glideMs)};

${Object.entries(t.fonts).map(([k, v]) => `constexpr const char* font_${k} = "res/fonts/${v}";`).join("\n")}

} // namespace tokens
} // namespace atlas
`;
fs.writeFileSync(path.join(ROOT, "plugin/src/ui/ThemeTokens.hpp"), out);
console.log("ThemeTokens.hpp written");
